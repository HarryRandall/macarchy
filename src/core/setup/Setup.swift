import Foundation

/// First-run setup and its undo.
///
/// Setup is explicit and previewable: `plan` describes every file it would
/// touch without changing anything. It writes the daemons' configs into
/// `Paths.configDirectory` and Macarchy's LaunchAgents start the daemons with
/// them, so a person's own configs are read, never changed. Only the tools a
/// person chose are configured; the others are left entirely alone. The
/// installers' agents are backed up before setup changes them; `uninstall`
/// puts those back, removes what did not exist before and clears the record,
/// so a later setup starts from whatever is there then.
public enum Setup {
    /// What to do with configuration a person already has.
    public enum Existing: String, Sendable, CaseIterable {
        /// Start from their configs, layered onto Macarchy's. Their top-level
        /// yabai settings move into Macarchy. The bar is always Macarchy's
        /// widgets; a sketchybarrc of their own is left as it is.
        case keep
        /// Start from Macarchy's defaults. Their configs stay where they are, unused.
        case replace
    }

    public struct Change: Sendable, Equatable, Identifiable {
        public enum Action: String, Sendable { case create, adopt, replace, include, link }
        public let path: URL
        public let action: Action
        public let detail: String
        public var id: String { path.path }
    }

    /// Whether setup has to run: it never has, or the bar it set up still
    /// has to move onto widgets.
    public static var isNeeded: Bool {
        !FileManager.default.fileExists(atPath: Paths.settings.path) || barNeedsMoving
    }

    // MARK: - Locations

    /// The shortcuts skhd runs with, edited by the Shortcuts page; see `Paths.skhdrc`.
    public static var skhdrc: URL { Paths.skhdrc }

    /// A config the person had before Macarchy, where the daemon looks by
    /// default. With `keep`, setup starts from it; it is never changed.
    static func ownConfig(_ candidates: [String]) -> URL? {
        candidates.map { Paths.home.appending(path: $0) }
            .first { FileManager.default.fileExists(atPath: $0.path) }
    }

    static var yabaiSource: URL? { ownConfig([".config/yabai/yabairc", ".yabairc"]) }
    static var skhdSource: URL? { ownConfig([".config/skhd/skhdrc", ".skhdrc"]) }
    static var sketchybarSource: URL? { ownConfig([".config/sketchybar/sketchybarrc"]) }
    /// Only an earlier version's file counts: borders is configured from settings.
    static var bordersSource: URL? { ownConfig([".config/borders/bordersrc"]) }

    static func isGenerated(_ url: URL) -> Bool {
        guard let text = try? String(contentsOf: url, encoding: .utf8) else { return false }
        return text.contains("# Generated by Macarchy.")
    }

    /// Hand-written content worth keeping: not empty and not already ours.
    static func adoptable(_ url: URL) -> String? {
        guard !isGenerated(url), let text = try? String(contentsOf: url, encoding: .utf8),
            !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty
        else { return nil }
        return text
    }

    // MARK: - Planning

    /// Every file setup would write for `choices`, and how. Reads only.
    public static func plan(_ choices: Choices) -> [Change] {
        func change(_ url: URL, source: URL?, _ adopt: String, _ create: String) -> Change {
            if isGenerated(url) {
                return Change(
                    path: url, action: .replace, detail: "Regenerated, keeping your region")
            }
            if let carried = carriedChange(url, source: source) { return carried }
            guard let source, let text = adoptable(source) else {
                return Change(path: url, action: .create, detail: create)
            }
            let existing = choices.existing(.yabai)
            if existing == .keep, let interpreter = foreignInterpreter(text) {
                return Change(
                    path: url, action: .adopt,
                    detail: "\(Paths.display(source)) runs with \(interpreter), so it cannot be "
                        + "kept and setup will stop. Convert it to bash or start from defaults")
            }
            return existing == .keep
                ? Change(path: url, action: .adopt, detail: adopt)
                : Change(
                    path: url, action: .create,
                    detail: "Starts from Macarchy's defaults; \(Paths.display(source)) is left "
                        + "as it is")
        }
        let tools = choices.tools
        var changes = [
            Change(
                path: Paths.appLink, action: .link,
                detail: "Points startup files at the installed app")
        ]
        if tools.contains(.yabai) {
            changes.append(
                change(
                    StartupConfiguration.yabairc.url, source: yabaiSource,
                    "Starts from your yabairc: simple layout values move into Macarchy and "
                        + "everything else is kept as written",
                    "Starts tiling with Macarchy's layout and rules"))
        }
        if tools.contains(.skhd) { changes.append(shortcutsChange(choices.existing(.skhd))) }
        if tools.contains(.sketchybar) { changes += barChanges() }
        if tools.contains(.borders) { changes.append(bordersChange()) }
        for daemon in choices.ordered {
            let installed = Paths.isInstalled(daemon.executableName)
            changes.append(
                Change(
                    path: DaemonAgents.plist(daemon), action: .create,
                    detail: "Starts \(daemon.displayName) at login with Macarchy's config"
                        + (installed ? "" : " once it is installed")
                        + ". Any agent it had is backed up and switched off when the services "
                        + "start"))
        }
        return changes
    }

    // MARK: - Running

    /// Performs the plan under the desktop lock, so two setups cannot
    /// interleave and back up each other's output as an original.
    /// A failing step throws `Interrupted` with the lines of the steps before it.
    public static func run(_ choices: Choices, app: URL?) async throws -> [String] {
        try checkCarriable(choices.tools)
        return try await OperationLock.run {
            if choices.tools.contains(.yabai), choices.existing(.yabai) == .keep {
                try await checkKeepable()
            }
            return try await runLocked(choices, app: app)
        }
    }

    static func runLocked(
        _ choices: Choices, app: URL?, report lines: [String] = []
    ) async throws
        -> [String]
    {
        var report = lines
        do {
            try await perform(choices, app: app, report: &report)
        } catch {
            throw Interrupted(lines: report, reason: error.localizedDescription)
        }
        return report
    }

    // The steps read top to bottom in the order they must happen. Each one
    // appends its line as soon as it has changed a file, so an `Interrupted`
    // failure still lists everything changed before it.
    private static func perform(
        _ choices: Choices, app: URL?, report: inout [String]
    ) async throws {
        let tools = choices.tools
        try BundledStartLauncher.validate(tools)
        let fm = FileManager.default
        for directory in [
            Paths.appRoot, Paths.themesDirectory, Paths.generatedDirectory, Paths.backupsDirectory,
            Paths.configDirectory, Paths.stateDirectory
        ] {
            try fm.createDirectory(at: directory, withIntermediateDirectories: true)
        }
        if let app { try link(app); report.append("Linked \(Paths.display(app))") }
        try installThemes(report: &report)

        let backups = Backups()
        let settings = SettingsStore()
        func note(_ line: String) { if !report.contains(line) { report.append(line) } }
        func generate(_ url: URL, _ outcome: GeneratedFile.Outcome) throws {
            let drift = try check(outcome, url.lastPathComponent)
            if outcome != .unchanged { note("Wrote \(Paths.display(url))") }
            report += drift
        }
        func updateSettings(_ edit: (inout SettingsDocument) throws -> Void) throws {
            let before = try? Data(contentsOf: settings.url)
            try settings.update(edit)
            if (try? Data(contentsOf: settings.url)) != before {
                note("Wrote \(Paths.display(settings.url))")
            }
        }
        try updateSettings(seedDefaults)

        if tools.contains(.yabai) {
            let yabairc = StartupConfiguration.yabairc.url
            let yabai = try await yabaiRegion(
                existing: choices.existing(.yabai), updateSettings: updateSettings)
            report += yabai.lines
            try generate(yabairc, StartupConfiguration().generateYabaiRC(adopting: yabai.region))
        }

        if tools.contains(.skhd) {
            try await seedShortcuts(existing: choices.existing(.skhd), report: &report)
        }

        if tools.contains(.sketchybar) {
            let sketchybarrc = StartupConfiguration.sketchybarrc.url
            let bar = try await barRegion(settings: settings, updateSettings: updateSettings)
            report += bar.lines
            try generate(
                sketchybarrc, StartupConfiguration().generateSketchybarRC(adopting: bar.region))
        }

        if tools.contains(.borders) {
            let bordersrc = StartupConfiguration.bordersrc.url
            let borders = try await bordersRegion()
            report += borders.lines
            try generate(
                bordersrc, StartupConfiguration().generateBordersRC(adopting: borders.region))
        }
        for daemon in choices.ordered where Paths.isInstalled(daemon.executableName) {
            try DaemonAgents.install(daemon, backups: backups, report: &report)
        }
        // Last, so the bar's snapshot above holds the settings as they were;
        // starting the services reads it.
        try updateSettings { $0.tools = choices.ordered.map(\.rawValue) }
    }

    /// Restores every original from backups and removes what setup created.
    /// Settings, themes and snapshots stay, so setting up again is lossless.
    public static func uninstall(
        integrations: Integrations = Integrations()
    ) async throws
        -> [String]
    {
        try await OperationLock.run {
            await DaemonAgents.stopAll(integrations: integrations)
            var report: [String] = []
            do {
                try uninstallLocked(into: &report)
            } catch {
                // The daemons were stopped for the restore; start whichever
                // agent each has now rather than leaving it stopped.
                await DaemonAgents.resume(integrations: integrations)
                guard !report.isEmpty else { throw error }
                throw ConfigurationError(
                    "Uninstall stopped part way: \(error.localizedDescription)\n"
                        + "Already done:\n" + report.map { "  \($0)" }.joined(separator: "\n")
                        + "\nFix the problem and run uninstall again to finish.")
            }
            await DaemonAgents.restoreReplaced(integrations: integrations)
            return report
        }
    }

    /// Each change is added to `report` as it is made, so a failure part way
    /// still tells the caller what was already put back.
    static func uninstallLocked(into report: inout [String]) throws {
        let fm = FileManager.default
        try Backups().restoreAll(into: &report)
        // Setup no longer adds the PATH line or Ghostty's include, but earlier
        // versions did, so restoring still takes them out.
        try NeovimSetup.uninstall(into: &report)
        for file in StartupConfiguration.all { try file.forget() }
        // A Ghostty file setup did not create still carries the include.
        for url in GhosttyConfig.loadedFiles {
            guard let text = try? String(contentsOf: url, encoding: .utf8),
                GhosttyConfig.hasInclude(text)
            else { continue }
            try GhosttyConfig.write(GhosttyConfig.removingInclude(from: text), to: url)
            report.append("Removed the Ghostty include from \(Paths.display(url))")
        }
        if (try? fm.destinationOfSymbolicLink(atPath: Paths.appLink.path)) != nil {
            try fm.removeItem(at: Paths.appLink)
        }
        // The launcher folder, once restoring has removed the launchers in it.
        let launchers = Paths.launcherDirectory
        if StartLauncher.folderIsUsable,
            let names = try? fm.contentsOfDirectory(atPath: launchers.path),
            names.allSatisfy({ $0 == ".DS_Store" })
        {
            try fm.removeItem(at: launchers)
            report.append("Removed \(Paths.display(launchers))")
        }
    }
}

extension Setup {
    /// Starts every chosen daemon that is installed from Macarchy's agent,
    /// switching off the agent it had before. A daemon setup has not given an
    /// agent yet is reported, not started some other way.
    public static func startServices(
        integrations: Integrations = Integrations()
    ) async
        -> [CommandResult]
    {
        var results: [CommandResult] = []
        for daemon in Daemon.allCases where daemon.isManaged {
            results.append(await startService(daemon, integrations: integrations))
        }
        return results
    }

    /// Starts one daemon the way `startServices` does, so the app's restart
    /// and `macarchy services` share it.
    public static func startService(
        _ daemon: Daemon, integrations: Integrations = Integrations()
    ) async -> CommandResult {
        guard DaemonAgents.isInstalled(daemon) else {
            return CommandResult(
                command: daemon.startCommand, status: 1,
                stderr: "Run setup so Macarchy can start \(daemon.displayName)")
        }
        return await DaemonAgents.start(daemon, integrations: integrations)
    }
}

extension Setup {
    /// After uninstall, hands each chosen daemon still installed back to its installer:
    /// restarts the agent it had before setup, or registers one the way its
    /// installer would.
    public static func returnServices(
        integrations: Integrations = Integrations()
    ) async
        -> [CommandResult]
    {
        var results: [CommandResult] = []
        for daemon in Daemon.allCases where daemon.isManaged {
            if daemon.isRegistered {
                results.append(await integrations.restart(daemon))
                continue
            }
            switch daemon {
            case .yabai, .skhd:
                results.append(await integrations.execute(daemon.executable, ["--start-service"]))
            case .sketchybar, .borders:
                guard Paths.isInstalled("brew") else {
                    results.append(
                        CommandResult(
                            command: "brew services start \(daemon.rawValue)", status: 1,
                            stderr: "Homebrew is needed to start \(daemon.displayName)"))
                    continue
                }
                results.append(
                    await integrations.execute(
                        Paths.executable("brew"), ["services", "start", daemon.rawValue]))
            }
        }
        return results
    }
}

extension Setup {
    /// Setup stopped partway. Files changed before the failure stay changed,
    /// so the lines describing them must reach the person with the reason.
    public struct Interrupted: LocalizedError, Sendable {
        public let lines: [String]
        public let reason: String
        public var errorDescription: String? { reason }
    }
}
