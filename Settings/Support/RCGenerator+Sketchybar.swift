import Foundation
import Desktop

extension RCGenerator {

    static let sketchybarKeys: [SettingKey] = [
        SettingKey(key: "height", env: "SKETCHYBAR_HEIGHT", fallback: "37"),
        SettingKey(key: "position", env: "SKETCHYBAR_POSITION", fallback: "top"),
        SettingKey(key: "padding_left", env: "SKETCHYBAR_PADDING_LEFT", fallback: "10"),
        SettingKey(key: "padding_right", env: "SKETCHYBAR_PADDING_RIGHT", fallback: "10"),
        SettingKey(key: "blur_radius", env: "SKETCHYBAR_BLUR_RADIUS", fallback: "0"),
        SettingKey(key: "corner_radius", env: "SKETCHYBAR_CORNER_RADIUS", fallback: "0"),
        SettingKey(key: "y_offset", env: "SKETCHYBAR_Y_OFFSET", fallback: "0"),
        SettingKey(key: "sticky", env: "SKETCHYBAR_STICKY", fallback: "on")
    ]

    static func envName(forBarKey key: String) -> String? {
        sketchybarKeys.first { $0.key == key }?.env
    }

    /// Splits sketchybarrc into the parts the app authors and the parts it must
    /// not touch.
    ///
    /// The bar, font and item defaults are chained into a *single* sketchybar
    /// invocation on purpose — separate calls each cost a repaint. That chain is
    /// preserved whole rather than picked apart: an earlier attempt to extract
    /// just the --bar flag group swallowed --load-font and --default with it,
    /// which would have cost the bar its app font and every item's styling.
    ///
    /// So geometry is applied as a second, small `--bar` call afterwards. It
    /// overrides the preserved values, costs one extra round trip at startup
    /// before any item exists, and cannot corrupt the chain.
    static func seedSketchybarRegions(from text: String) -> (setup: String, items: String) {
        var setup: [String] = []
        var items: [String] = []

        for raw in text.split(separator: "\n", omittingEmptySubsequences: false) {
            let line = String(raw)
            let trimmed = line.trimmingCharacters(in: .whitespaces)
            if trimmed.hasPrefix("#!") { continue }
            if trimmed.hasPrefix("source \"$ITEM_DIR") { items.append(line); continue }
            if trimmed.hasPrefix("sketchybar --update") { continue }
            setup.append(line)
        }

        return (Self.tidy(setup), Self.tidy(items))
    }

    func generateSketchybarRC() {
        let file = Self.sketchybarrc
        var kept = file.preservedRegions()

        if kept["setup"] == nil || kept["items"] == nil,
            let existing = try? String(contentsOf: file.url, encoding: .utf8) {
            let seeded = Self.seedSketchybarRegions(from: existing)
            if kept["setup"] == nil { kept["setup"] = seeded.setup }
            if kept["items"] == nil { kept["items"] = seeded.items }
        }

        let geometry = Self.sketchybarKeys
            .map { "  \($0.key)=\"${\($0.env):-\($0.fallback)}\"" }
            .joined(separator: " \\\n")

        let content = """
            #!/bin/bash
            # Generated by Macarchy Settings — edits here are reported, not silently kept.
            #
            # Bar geometry resolves from settings.env at run time. Everything inside
            # macarchy:keep is yours and survives regeneration: the chained setup
            # invocation, the item defaults and the item sourcing. Plugin scripts are
            # programs, not configuration, and are only ever referenced from here.

            SETTINGS_ENV="$HOME/.config/macarchy-settings/settings.env"
            if [ -f "$SETTINGS_ENV" ]; then
              # shellcheck source=/dev/null
              source "$SETTINGS_ENV"
            fi

            \(keepBlock("setup", from: kept))

            # Bar geometry — owned by the Menu Bar pane. Applied separately so the
            # invocation above stays intact; this runs before any item exists.
            sketchybar --bar \\
            \(geometry)

            \(keepBlock("items", from: kept))

            sketchybar --update

            """

        record("sketchybarrc", file.write(content, reason: "menu bar settings changed"))
    }
}
