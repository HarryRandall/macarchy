import Foundation

/// Owns ~/.config/macarchy/settings.env — a generated KEY=value file that the
/// rc scripts source, the same way bordersrc already sources theme.env.
///
/// The app never writes shell logic and never parses an rc script, so hand-authored
/// config and generated config can coexist without racing each other.
public struct SettingsEnv: Sendable {
    public let url: URL
    private let snapshots: SnapshotStore

    public init(url: URL = Paths.settingsEnv, snapshots: SnapshotStore = SnapshotStore()) {
        self.url = url
        self.snapshots = snapshots
    }

    private static let header = """
        # Generated by Macarchy Settings — do not edit by hand.
        # Sourced by bordersrc, yabairc and sketchybarrc.

        """

    public func load() -> [String: String] {
        EnvFile.parse(url)
    }

    public func write(_ values: [String: String]) throws {
        // Capture the outgoing version before overwriting it.
        try? snapshots.capture([url], reason: "settings.env write")

        try FileManager.default.createDirectory(
            at: url.deletingLastPathComponent(), withIntermediateDirectories: true)

        try EnvFile.render(values, header: Self.header)
            .write(to: url, atomically: true, encoding: .utf8)
    }

    public func set(_ key: String, _ value: String) throws {
        var values = load()
        values[key] = value
        try write(values)
    }
}
