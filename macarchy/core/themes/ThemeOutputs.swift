import Foundation

/// Pure renderers shared by theme application and parity tests.
public struct ThemeOutputs: Sendable {
    public let theme: Theme
    public let ghostty: String
    public init(theme: Theme, ghostty: String) { self.theme = theme; self.ghostty = ghostty }
    public func colour(_ key: String, fallback: String) -> String {
        for line in ghostty.split(separator: "\n") {
            let parts = line.split(separator: "=", maxSplits: 1).map {
                $0.trimmingCharacters(in: .whitespaces)
            }
            if parts.count == 2, parts[0] == key,
                parts[1].range(of: "^#[0-9a-fA-F]{6}$", options: .regularExpression) != nil
            {
                return parts[1]
            }
        }
        return fallback
    }
    public func palette(_ index: Int, fallback: String) -> String {
        for line in ghostty.split(separator: "\n") {
            let parts = line.split(separator: "=", maxSplits: 2).map {
                $0.trimmingCharacters(in: .whitespaces)
            }
            if parts.count == 3, parts[0] == "palette", Int(parts[1]) == index,
                parts[2].range(of: "^#[0-9a-fA-F]{6}$", options: .regularExpression) != nil
            {
                return parts[2]
            }
        }
        return fallback
    }
    public var barAccent: String {
        theme.colors.borderActive ?? "0xff"
            + palette(4, fallback: colour("foreground", fallback: "#ffffff")).dropFirst()
    }
    public var barText: String {
        theme.colors.sketchybarText ?? "0xff"
            + colour("foreground", fallback: theme.dark ? "#ffffff" : "#000000").dropFirst()
    }
    public var barBackground: String { theme.colors.sketchybarBar ?? "0x00000000" }
    public var nvim: String {
        switch theme.name {
        case "awakening", "blackgold", "matte-black": "gruvbox"
        case "midnight", "carbonfox": "tokyonight-night"
        case "lumon": "rose-pine-dawn"
        default: theme.apps.nvimColorscheme ?? "tokyonight"
        }
    }
    public var shell: String {
        let palette4 = palette(4, fallback: "")
        let border = theme.colors.borderActive.flatMap {
            $0.lowercased().hasPrefix("0xff") ? String($0.dropFirst(4)) : nil
        }
        let candidates = [theme.colors.firefoxAccent, border, palette4].compactMap { $0 }.map {
            $0.replacingOccurrences(of: "#", with: "")
        }
        var index = 4
        var accent = palette4.replacingOccurrences(of: "#", with: "")
        search: for candidate in candidates {
            for slot in 0...255
            where palette(slot, fallback: "").lowercased() == "#" + candidate.lowercased() {
                index = slot; accent = candidate; break search
            }
        }
        let foreground = theme.dark ? "ffffff" : "000000"
        if accent.isEmpty { accent = foreground }
        return """
            # Auto-generated by theme-switch. Do not edit.
            export EZA_COLORS='di=38;5;\(index):ex=1;38;5;\(index):ln=38;5;8:xx=38;5;8'
            export MACARCHY_ACCENT_IDX='\(index)'
            export MACARCHY_FG_IDX='\(theme.dark ? 15 : 0)'
            export MACARCHY_ACCENT='#\(accent)'
            export MACARCHY_FG='#\(foreground)'
            export MACARCHY_DARK_MODE='\(theme.dark)'

            """
    }
}
