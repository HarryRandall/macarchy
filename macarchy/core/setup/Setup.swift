import Foundation

/// First-run setup and its undo.
///
/// Setup is explicit and previewable: `plan` describes every file it would
/// touch without changing anything. Running it backs up each existing file
/// once, into `~/.config/macarchy/backups`, before writing. `uninstall` puts
/// those originals back and removes files that did not exist before.
public enum Setup {
    /// What to do with configuration a person already has.
    public enum Existing: String, Sendable, CaseIterable {
        /// Keep their commands, layered onto Macarchy's. Their yabai settings
        /// move into Macarchy; a hand-built bar replaces Macarchy's bar.
        case keep
        /// Start from Macarchy's defaults. The originals stay in backups.
        case replace
    }

    public struct Change: Sendable, Equatable, Identifiable {
        public enum Action: String, Sendable { case create, adopt, replace, include, link }
        public let path: URL
        public let action: Action
        public let detail: String
        public var id: String { path.path }
    }

    public static var skhdrc: URL { Paths.home.appending(path: ".config/skhd/skhdrc") }

    /// Every file setup would write, and how. Reads only.
    public static func plan(existing: Existing) -> [Change] {
        let fm = FileManager.default
        func change(_ url: URL, _ adopt: String, _ create: String) -> Change {
            guard fm.fileExists(atPath: url.path) else {
                return Change(path: url, action: .create, detail: create)
            }
            if isGenerated(url) {
                return Change(
                    path: url, action: .replace, detail: "Regenerated, keeping your region")
            }
            return existing == .keep
                ? Change(path: url, action: .adopt, detail: adopt)
                : Change(path: url, action: .replace, detail: "Replaced; the original is backed up")
        }
        var changes = [
            Change(
                path: Paths.appLink, action: .link,
                detail: "Points startup files at the installed app"),
            change(
                StartupConfiguration.yabairc.url,
                "Layout values move into Macarchy; your other commands are kept",
                "Starts tiling with Macarchy's layout and rules"),
            change(
                skhdrc, "Your shortcuts are kept as they are",
                "Installs Macarchy's default shortcuts"),
            change(
                StartupConfiguration.sketchybarrc.url,
                "Your bar is kept; Macarchy's bar stays off",
                "Installs Macarchy's menu bar"),
            change(
                StartupConfiguration.bordersrc.url, "Replaced; borders follow the theme",
                "Draws window borders in theme colours")
        ]
        if ghosttyWanted {
            changes.append(
                Change(
                    path: GhosttyConfig.configURL, action: .include,
                    detail: "Adds one line so Ghostty uses theme colours"))
        }
        return changes
    }

    /// Ghostty is themed when it is installed or already configured.
    static var ghosttyWanted: Bool {
        let fm = FileManager.default
        return fm.fileExists(atPath: GhosttyConfig.configURL.path)
            || Paths.hasApplication("Ghostty")
            || Paths.isInstalled("ghostty")
    }

    static func isGenerated(_ url: URL) -> Bool {
        guard let text = try? String(contentsOf: url, encoding: .utf8) else { return false }
        return text.contains("# Generated by Macarchy.")
    }

    // MARK: - Running

    /// Performs the plan. `app` is the bundle to link, normally the running app.
    /// The order matters: back up, then write, so a failure leaves originals safe.
    public static func run(existing: Existing, app: URL?) throws -> [String] {
        let fm = FileManager.default
        var report: [String] = []
        for directory in [
            Paths.appRoot, Paths.themesDirectory, Paths.generatedDirectory, Paths.backupsDirectory
        ] {
            try fm.createDirectory(at: directory, withIntermediateDirectories: true)
        }
        if let app { try link(app); report.append("Linked \(Paths.display(app))") }
        report += try installThemes()

        let backups = Backups()
        // Re-running setup must not reseed files the person has since edited.
        let firstRun = !backups.hasRecord(for: skhdrc)
        try backups.save(
            [
                StartupConfiguration.yabairc.url, skhdrc, StartupConfiguration.sketchybarrc.url,
                StartupConfiguration.bordersrc.url, GhosttyConfig.configURL
            ])

        let settings = SettingsStore()
        try settings.update { document in
            if document.currentTheme == nil { document.currentTheme = defaultTheme }
        }

        // yabai: move recognised settings into JSON, keep the rest.
        var yabaiKept = ""
        if firstRun, existing == .keep, let text = adoptable(StartupConfiguration.yabairc.url) {
            let adopted = StartupConfiguration.adoptYabai(text)
            try settings.update { $0.mergeFlat(adopted.values) }
            yabaiKept = adopted.kept
            report.append("Moved \(adopted.values.count) yabai settings into Macarchy")
        }
        try check(
            StartupConfiguration().generateYabaiRC(
                adopting: isGenerated(StartupConfiguration.yabairc.url) ? nil : yabaiKept))

        // skhd: the file stays the person's; Macarchy only seeds it.
        let shortcutsMissing = !fm.fileExists(atPath: skhdrc.path)
        if shortcutsMissing || (firstRun && (existing == .replace || adoptable(skhdrc) == nil)) {
            try installDefaultShortcuts()
            report.append("Installed default shortcuts")
        }

        // SketchyBar: a hand-built bar is kept whole, with Macarchy's switched off.
        var barKept: String?
        if firstRun, existing == .keep, let text = adoptable(StartupConfiguration.sketchybarrc.url)
        {
            barKept = StartupConfiguration.tidy(
                text.components(separatedBy: "\n").filter { !$0.hasPrefix("#!") })
            try settings.update { $0.bundledBar = false }
            report.append("Kept your menu bar")
        } else if firstRun {
            try settings.update { $0.bundledBar = true }
        }
        try check(StartupConfiguration().generateSketchybarRC(adopting: barKept))
        try check(StartupConfiguration().generateBordersRC())

        if ghosttyWanted {
            let current = (try? String(contentsOf: GhosttyConfig.configURL, encoding: .utf8)) ?? ""
            let updated = GhosttyConfig.addingInclude(to: current)
            if updated != current {
                try fm.createDirectory(
                    at: GhosttyConfig.configURL.deletingLastPathComponent(),
                    withIntermediateDirectories: true)
                try updated.write(to: GhosttyConfig.configURL, atomically: true, encoding: .utf8)
                report.append("Added the theme include to Ghostty")
            }
        }
        return report
    }

    /// Restores every original from backups and removes what setup created.
    /// Settings, themes and snapshots stay, so setting up again is lossless.
    public static func uninstall() throws -> [String] {
        let fm = FileManager.default
        var report = try Backups().restoreAll()
        if let text = try? String(contentsOf: GhosttyConfig.configURL, encoding: .utf8),
            GhosttyConfig.hasInclude(text)
        {
            try GhosttyConfig.removingInclude(from: text).write(
                to: GhosttyConfig.configURL, atomically: true, encoding: .utf8)
            report.append("Removed the Ghostty include")
        }
        if (try? fm.destinationOfSymbolicLink(atPath: Paths.appLink.path)) != nil {
            try fm.removeItem(at: Paths.appLink)
        }
        return report
    }

    // MARK: - Steps

    static let defaultTheme = "midnight"

    /// Points the app link at `app`, replacing a stale link but never a real file.
    public static func link(_ app: URL) throws {
        let fm = FileManager.default
        let target = app.resolvingSymlinksInPath().path
        if let existing = try? fm.destinationOfSymbolicLink(atPath: Paths.appLink.path) {
            if existing == target { return }
            try fm.removeItem(at: Paths.appLink)
        } else if fm.fileExists(atPath: Paths.appLink.path) {
            throw ConfigurationError("\(Paths.display(Paths.appLink)) exists and is not a link")
        }
        try fm.createSymbolicLink(atPath: Paths.appLink.path, withDestinationPath: target)
    }

    /// Copies bundled themes that are not installed yet. Installed themes,
    /// including edited copies of bundled ones, are never overwritten.
    static func installThemes() throws -> [String] {
        let fm = FileManager.default
        guard let source = Paths.resources?.appending(path: "themes") else {
            throw ConfigurationError("Bundled themes are missing. Reinstall Macarchy.")
        }
        var installed: [String] = []
        for theme in try fm.contentsOfDirectory(at: source, includingPropertiesForKeys: nil)
        where Theme.load(from: theme) != nil {
            let destination = Paths.themesDirectory.appending(path: theme.lastPathComponent)
            guard !fm.fileExists(atPath: destination.path) else { continue }
            try fm.copyItem(at: theme, to: destination)
            installed.append(theme.lastPathComponent)
        }
        return installed.isEmpty ? [] : ["Installed themes: \(installed.joined(separator: ", "))"]
    }

    public static func installDefaultShortcuts() throws {
        guard let source = Paths.resources?.appending(path: "skhd/skhdrc") else {
            throw ConfigurationError("Default shortcuts are missing. Reinstall Macarchy.")
        }
        let fm = FileManager.default
        try fm.createDirectory(
            at: skhdrc.deletingLastPathComponent(), withIntermediateDirectories: true)
        let text = try String(contentsOf: source, encoding: .utf8)
        try text.write(to: skhdrc, atomically: true, encoding: .utf8)
    }

    /// Hand-written content worth keeping: not empty and not already ours.
    static func adoptable(_ url: URL) -> String? {
        guard !isGenerated(url), let text = try? String(contentsOf: url, encoding: .utf8),
            !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty
        else { return nil }
        return text
    }

    static func check(_ outcome: GeneratedFile.Outcome) throws {
        if case .failed(let message) = outcome { throw ConfigurationError(message) }
    }
}

extension Setup {
    /// Starts every installed daemon: registers its LaunchAgent if needed,
    /// otherwise restarts it so it reads the new startup files.
    public static func startServices(
        integrations: Integrations = Integrations()
    ) async
        -> [CommandResult]
    {
        var results: [CommandResult] = []
        for daemon in Daemon.allCases where Paths.isInstalled(daemon.executableName) {
            if daemon.isRegistered {
                results.append(await integrations.restart(daemon))
                continue
            }
            switch daemon {
            case .yabai, .skhd:
                results.append(await integrations.execute(daemon.executable, ["--start-service"]))
            case .sketchybar, .borders:
                guard Paths.isInstalled("brew") else {
                    results.append(
                        CommandResult(
                            command: daemon.startCommand, status: 1,
                            stderr: "Homebrew is needed to start \(daemon.displayName)"))
                    continue
                }
                results.append(
                    await integrations.execute(
                        Paths.executable("brew"), ["services", "start", daemon.rawValue]))
            }
        }
        return results
    }
}
