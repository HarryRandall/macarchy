import Foundation

/// The startup files the daemons read from their fixed locations.
///
/// Each one only hands over to the Macarchy command, which reads settings.json,
/// so they are correct at login whether or not the app is running. Anything
/// inside the `yours` region is the person's own and survives regeneration.
public struct StartupConfiguration: Sendable {
    public init() {}

    public static var bordersrc: GeneratedFile {
        GeneratedFile(url: Paths.home.appending(path: ".config/borders/bordersrc"))
    }

    public static var sketchybarrc: GeneratedFile {
        GeneratedFile(url: Paths.home.appending(path: ".config/sketchybar/sketchybarrc"))
    }

    public static var yabairc: GeneratedFile {
        GeneratedFile(url: Paths.home.appending(path: ".config/yabai/yabairc"))
    }

    public static var all: [GeneratedFile] { [yabairc, sketchybarrc, bordersrc] }

    public var driftedFiles: [String] {
        Self.all.filter(\.hasDrifted).map { $0.url.lastPathComponent }
    }

    static let yoursRegion = "yours"

    static func header(_ purpose: String) -> String {
        """
        #!/bin/bash
        # Generated by Macarchy. \(purpose)
        #
        # Add your own commands inside the region below; it is kept when this
        # file is regenerated. Changes anywhere else are reported and replaced.

        """
    }

    /// The person's region, from this file or from content being adopted.
    func yours(_ file: GeneratedFile, adopting: String?) -> String {
        if let adopting { return adopting }
        return file.preservedRegions()[Self.yoursRegion] ?? ""
    }

    func region(_ body: String) -> String {
        "\(GeneratedFile.beginKeep) \(Self.yoursRegion)\n\(body)\n\(GeneratedFile.endKeep)"
    }

    /// Trims leading and trailing blank lines from adopted content.
    static func tidy(_ lines: [String]) -> String {
        var out = lines
        while out.first?.trimmingCharacters(in: .whitespaces).isEmpty == true { out.removeFirst() }
        while out.last?.trimmingCharacters(in: .whitespaces).isEmpty == true { out.removeLast() }
        return out.joined(separator: "\n")
    }

    // MARK: - borders

    /// borders is configured entirely from settings, so nothing is adopted.
    @discardableResult
    public func generateBordersRC() -> GeneratedFile.Outcome {
        let file = Self.bordersrc
        let content =
            Self.header("Borders follow the active theme and the Borders page.")
            + region(yours(file, adopting: nil)) + "\n\n"
            + "exec \(Paths.cliInShell) startup borders\n"
        return file.write(content, reason: "borders startup changed")
    }
}
