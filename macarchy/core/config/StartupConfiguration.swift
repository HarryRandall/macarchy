import Foundation

public struct StartupConfiguration: Sendable {
    public init() {}
    public static var bordersrc: GeneratedFile {
        GeneratedFile(url: Paths.home.appending(path: ".config/borders/bordersrc"))
    }

    public static var sketchybarrc: GeneratedFile {
        GeneratedFile(url: Paths.home.appending(path: ".config/sketchybar/sketchybarrc"))
    }

    public static var yabairc: GeneratedFile {
        GeneratedFile(url: Paths.home.appending(path: ".config/yabai/yabairc"))
    }

    public var driftedFiles: [String] {
        [Self.bordersrc, Self.yabairc, Self.sketchybarrc]
            .filter(\.hasDrifted)
            .map { $0.url.lastPathComponent }
    }

    public static let header = """
        #!/bin/bash
        # Generated by Macarchy — edits here are reported, not silently kept.
        #
        # Values resolve from JSON through the macarchy command, so
        # this works at login whether or not the app is running. Regions marked
        # "macarchy:keep" are preserved across regeneration.

        """

    // MARK: - Shared

    /// Re-emits a preserved region, or an empty one if the file has never been
    /// generated. Used by every generator, which is why it lives here.
    func keepBlock(_ name: String, from kept: [String: String]) -> String {
        "\(GeneratedFile.beginKeep) \(name)\n\(kept[name] ?? "")\n\(GeneratedFile.endKeep)"
    }

    /// Trims leading and trailing blank lines from a seeded region.
    static func tidy(_ lines: [String]) -> String {
        var out = lines
        while out.first?.trimmingCharacters(in: .whitespaces).isEmpty == true { out.removeFirst() }
        while out.last?.trimmingCharacters(in: .whitespaces).isEmpty == true { out.removeLast() }
        return out.joined(separator: "\n")
    }

}
