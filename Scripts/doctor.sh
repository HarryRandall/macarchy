#!/bin/bash
# macarchy doctor — assert the desktop is in a working state.
#
# This is the gate for every migration phase: run it before a change and after.
# A phase that leaves doctor failing gets reverted, not patched forward.
#
# Exit 0 = healthy, 1 = something is broken.

set -uo pipefail

PASS=0; FAIL=0; WARN=0
NEW_ROOT="$HOME/.config/macarchy-settings"

ok()   { printf "  \033[32m✓\033[0m %s\n" "$1"; PASS=$((PASS+1)); }
bad()  { printf "  \033[31m✗\033[0m %s\n" "$1"; FAIL=$((FAIL+1)); }
warn() { printf "  \033[33m!\033[0m %s\n" "$1"; WARN=$((WARN+1)); }
head_() { printf "\n\033[1m%s\033[0m\n" "$1"; }

head_ "Daemons"
for d in yabai borders sketchybar skhd; do
  if pgrep -x "$d" >/dev/null 2>&1 || pgrep -f "macarchy-$d" >/dev/null 2>&1; then
    ok "$d running"
  else
    bad "$d not running"
  fi
done

head_ "Daemons answer"
if v=$(yabai -m config window_gap 2>/dev/null) && [ -n "$v" ]; then
  ok "yabai responds (window_gap=$v)"
else
  bad "yabai not responding to queries"
fi

if sketchybar --query bar >/dev/null 2>&1; then
  ok "sketchybar responds to --query"
else
  bad "sketchybar not responding to --query"
fi

# borders has no query verb, so the best available check is which binary is live.
if pgrep -lf macarchy-borders >/dev/null 2>&1; then
  ok "borders running the local patched build"
elif pgrep -x borders >/dev/null 2>&1; then
  warn "borders running the Homebrew build, not the local patched one"
else
  bad "no borders process"
fi

head_ "Config tree"
[ -d "$NEW_ROOT" ] && ok "app root exists ($NEW_ROOT)" || bad "missing $NEW_ROOT"
[ -f "$NEW_ROOT/settings.env" ] && ok "settings.env present" || bad "missing settings.env"

if [ -L "$HOME/.config/themes" ] && [ -d "$HOME/.config/themes" ]; then
  ok "~/.config/themes symlink resolves"
elif [ -d "$HOME/.config/themes" ]; then
  warn "~/.config/themes is a real directory, not the expected symlink"
else
  bad "~/.config/themes does not resolve"
fi

if grep -q "macarchy-settings/settings.env" "$HOME/.config/borders/bordersrc" 2>/dev/null; then
  ok "bordersrc sources the new settings.env"
else
  bad "bordersrc does not reference the new settings.env"
fi

if head -3 "$HOME/.config/borders/bordersrc" 2>/dev/null | grep -q "Generated by Macarchy Settings"; then
  ok "bordersrc is app-generated"
else
  bad "bordersrc is not app-generated — something else rewrote it"
fi

if bash -n "$HOME/.config/borders/bordersrc" 2>/dev/null; then
  ok "bordersrc is valid shell"
else
  bad "bordersrc has a syntax error"
fi

# Removing Raycast integration once also deleted the next function declaration.
# Daemon health alone cannot detect a broken script until the next theme switch.
if bash -n "$HOME/.local/bin/theme-switch" 2>/dev/null; then
  ok "theme-switch is valid shell"
else
  bad "theme-switch has a syntax error"
fi

# theme-switch used to regenerate bordersrc on every switch, silently reverting
# whatever the app wrote. Assert that generator stays dead.
if grep -A4 "^write_borders_config()" "$HOME/.local/bin/theme-switch" 2>/dev/null | grep -q "sole author"; then
  ok "theme-switch no longer generates bordersrc"
else
  bad "theme-switch is generating bordersrc again — dual ownership is back"
fi

if head -3 "$HOME/.config/yabai/yabairc" 2>/dev/null | grep -q "Generated by Macarchy Settings"; then
  ok "yabairc is app-generated"
else
  warn "yabairc is not app-generated yet"
fi

if bash -n "$HOME/.config/yabai/yabairc" 2>/dev/null; then
  ok "yabairc is valid shell"
else
  bad "yabairc has a syntax error"
fi

# The scripting addition and signal handlers live in keep regions. If a
# regeneration ever drops them, yabai comes up crippled but still "running".
if grep -q "yabai --load-sa" "$HOME/.config/yabai/yabairc" 2>/dev/null \
   && grep -q "signal --add" "$HOME/.config/yabai/yabairc" 2>/dev/null; then
  ok "yabairc keep regions intact (scripting addition + signals)"
else
  bad "yabairc lost its scripting addition or signal handlers"
fi

n_sig=$(yabai -m signal --list 2>/dev/null | python3 -c "import json,sys; print(len(json.load(sys.stdin)))" 2>/dev/null || echo 0)
[ "$n_sig" -ge 7 ] && ok "yabai has $n_sig signals registered" || bad "yabai has only $n_sig signals"

SBRC="$HOME/.config/sketchybar/sketchybarrc"
if head -3 "$SBRC" 2>/dev/null | grep -q "Generated by Macarchy Settings"; then
  ok "sketchybarrc is app-generated"
else
  warn "sketchybarrc is not app-generated yet"
fi

if bash -n "$SBRC" 2>/dev/null; then
  ok "sketchybarrc is valid shell"
else
  bad "sketchybarrc has a syntax error"
fi

# The bar, font and item defaults are one chained invocation. An earlier
# generator tried to extract just the --bar group and swallowed --load-font and
# --default with it, which costs the bar its app font and every item's styling
# while leaving sketchybar "running" and the bar visible.
missing=""
grep -q "load-font" "$SBRC" 2>/dev/null || missing="$missing --load-font"
grep -q "icon.font" "$SBRC" 2>/dev/null || missing="$missing --default"
n_items=$(grep -c 'source "\$ITEM_DIR' "$SBRC" 2>/dev/null | head -1)
n_items=${n_items:-0}
[ "$n_items" -gt 0 ] || missing="$missing item-sourcing"
if [ -z "$missing" ]; then
  ok "sketchybarrc keep regions intact (font, defaults, $n_items items)"
else
  bad "sketchybarrc lost:$missing"
fi

head_ "Themes"
THEMES_DIR="$NEW_ROOT/themes"
CURRENT="$(cat "$THEMES_DIR/.current" 2>/dev/null || true)"
if [ -n "$CURRENT" ] && [ -d "$THEMES_DIR/$CURRENT" ]; then
  ok "current theme resolves ($CURRENT)"
else
  bad "current theme does not resolve (got '${CURRENT:-empty}')"
fi

total=0; withjson=0; badjson=0
for d in "$THEMES_DIR"/*/; do
  [ -d "$d" ] || continue
  total=$((total+1))
  if [ -f "$d/theme.json" ]; then
    withjson=$((withjson+1))
    python3 -c "import json,sys; json.load(open(sys.argv[1]))" "$d/theme.json" 2>/dev/null \
      || { badjson=$((badjson+1)); bad "invalid JSON: $(basename "$d")/theme.json"; }
  fi
done
[ "$total" -gt 0 ] && ok "$total themes installed" || bad "no themes found"
if [ "$withjson" -eq "$total" ] && [ "$badjson" -eq 0 ]; then
  ok "all $total themes have valid theme.json"
else
  warn "$withjson/$total themes have a manifest, $badjson invalid"
fi

# theme.env is generated from theme.json. If they diverge, the shell and the UI
# disagree about a theme without anything erroring.
drift=$(python3 - "$THEMES_DIR" <<'PYEOF'
import json, os, sys
root = sys.argv[1]
MAP = {"BORDER_ACTIVE": ("colors","borderActive"), "BORDER_INACTIVE": ("colors","borderInactive"),
       "SKETCHYBAR_BAR_COLOR": ("colors","sketchybarBar"),
       "SKETCHYBAR_TEXT_COLOR": ("colors","sketchybarText"),
       "FIREFOX_ACCENT": ("colors","firefoxAccent"), "NVIM_COLORSCHEME": ("apps","nvimColorscheme")}
DROPPED = {"BORDER_WIDTH"}
bad = 0
for name in sorted(os.listdir(root)):
    d = os.path.join(root, name)
    env_p, json_p = os.path.join(d, "theme.env"), os.path.join(d, "theme.json")
    if not (os.path.isfile(env_p) and os.path.isfile(json_p)):
        continue
    env = {}
    for line in open(env_p):
        line = line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        k, v = line.split("=", 1)
        env[k] = v.strip('"')
    m = json.load(open(json_p))
    for k, v in env.items():
        if k in DROPPED:
            continue
        if k == "DARK_MODE":
            if str(m.get("dark")).lower() != v.lower(): bad += 1
        elif k == "WALLPAPER":
            if m.get("wallpaper") != v: bad += 1
        elif k in MAP:
            sec, key = MAP[k]
            if m.get(sec, {}).get(key) != v: bad += 1
        else:
            bad += 1
print(bad)
PYEOF
)
[ "${drift:-0}" -eq 0 ] && ok "theme.json and theme.env agree" \
                        || bad "$drift theme values differ between theme.json and theme.env"

head_ "Wallpaper"
# A grey desktop has been a real failure mode here, so check the file resolves
# and that something is actually set.
WALL_REL="$(python3 -c "
import json,sys,os
p=sys.argv[1]
try:
    d=json.load(open(os.path.join(p,'.backgrounds.json')))
    print(d.get(sys.argv[2],''))
except Exception:
    print('')
" "$THEMES_DIR" "$CURRENT" 2>/dev/null)"
if [ -z "$WALL_REL" ] && [ -f "$THEMES_DIR/$CURRENT/theme.json" ]; then
  WALL_REL="$(python3 -c "
import json,sys
print(json.load(open(sys.argv[1])).get('wallpaper',''))
" "$THEMES_DIR/$CURRENT/theme.json" 2>/dev/null)"
fi
if [ -n "$WALL_REL" ] && [ -f "$THEMES_DIR/$CURRENT/$WALL_REL" ]; then
  ok "wallpaper file resolves ($WALL_REL)"
else
  bad "wallpaper for '$CURRENT' does not resolve ('${WALL_REL:-none}')"
fi

if command -v desktoppr >/dev/null 2>&1; then
  cur="$(desktoppr 2>/dev/null | head -1)"
  if [ -n "$cur" ] && [ -f "$cur" ]; then
    ok "desktop wallpaper is set"
  else
    warn "desktoppr reports no wallpaper — the grey-desktop failure mode"
  fi
fi

head_ "Ported surfaces"
if [ -x "$HOME/.local/bin/macarchy" ]; then
  ok "macarchy CLI installed"
else
  bad "macarchy CLI missing — theme-switch will skip ported surfaces"
fi

# Both entry points must run one implementation. If theme-switch grows its own
# ghostty handling back, the hotkey and the GUI can disagree about a theme.
if grep -q "macarchy\" ghostty" "$HOME/.local/bin/theme-switch" 2>/dev/null; then
  ok "theme-switch delegates ghostty to the CLI"
else
  bad "theme-switch is handling ghostty itself again"
fi

# Exactly one theme block, and nothing theme-owned leaking above it.
n_marker=$(grep -c "THEME COLORS" "$HOME/.config/ghostty/config" 2>/dev/null | head -1)
n_marker=${n_marker:-0}
[ "$n_marker" -eq 1 ] && ok "ghostty config has one theme block" \
                      || bad "ghostty config has $n_marker theme blocks"

leaked=$(sed -n '1,/THEME COLORS/p' "$HOME/.config/ghostty/config" 2>/dev/null \
         | grep -cE "^(background|foreground|palette|theme)[[:space:]]*=" | head -1)
leaked=${leaked:-0}
[ "$leaked" -eq 0 ] && ok "no theme colours leaked above the marker" \
                    || bad "$leaked theme-owned lines above the marker"

head_ "Hotkeys"
if [ -f "$HOME/.config/skhd/skhdrc" ]; then
  n=$(grep -cE '^[^#[:space:]].*:' "$HOME/.config/skhd/skhdrc" 2>/dev/null | head -1)
  n=${n:-0}
  [ "$n" -gt 0 ] && ok "skhdrc parses ($n bindings)" || bad "skhdrc has no bindings"
else
  bad "skhdrc missing"
fi

head_ "Window rules"
STATE="$HOME/.config/yabai/float_state.json"
if python3 -c "import json,sys; d=json.load(open(sys.argv[1])); sys.exit(0 if isinstance(d,list) else 1)" "$STATE" 2>/dev/null; then
  n_float=$(python3 -c "import json,sys; print(len(json.load(open(sys.argv[1]))))" "$STATE")
  ok "float_state.json valid ($n_float apps)"
else
  bad "float_state.json missing or not a JSON array"
fi

# Every app in the JSON should be loaded as a labelled rule. A mismatch means
# sync_float_rules.sh did not run, and those apps will tile on next launch.
n_labelled=$(yabai -m rule --list 2>/dev/null \
  | python3 -c "import json,sys; print(sum(1 for r in json.load(sys.stdin) if (r.get('label') or '').startswith('float_persist_')))" 2>/dev/null || echo 0)
if [ "${n_labelled:-0}" -ge "${n_float:-0}" ]; then
  ok "$n_labelled float rules loaded in yabai"
else
  warn "$n_labelled float rules loaded but $n_float in float_state.json — run sync_float_rules.sh"
fi

head_ "Borders source"
if git -C "$HOME/projects/jankyborders-local" rev-parse --git-dir >/dev/null 2>&1; then
  ok "borders fork is under version control ($(git -C "$HOME/projects/jankyborders-local" rev-list --count HEAD) commits)"
else
  bad "borders fork is NOT under version control"
fi

printf "\n\033[1m%d passed, %d failed, %d warnings\033[0m\n" "$PASS" "$FAIL" "$WARN"
[ "$FAIL" -eq 0 ] || exit 1
