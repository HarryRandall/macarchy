import Foundation
import MacarchyKit

extension RCGenerator {

    /// yabai config keys the app owns, with the settings.env variable each
    /// resolves from and the fallback if nothing has been set.
    static func envName(forYabaiKey key: String) -> String? {
        yabaiKeys.first { $0.key == key }?.env
    }

    static let yabaiKeys: [ConfigKey] = [
        ConfigKey(key: "layout", env: "YABAI_LAYOUT", fallback: "bsp"),
        ConfigKey(key: "window_insertion_point", env: "YABAI_INSERTION_POINT", fallback: "last"),
        ConfigKey(key: "window_placement", env: "YABAI_WINDOW_PLACEMENT", fallback: "second_child"),
        ConfigKey(key: "split_type", env: "YABAI_SPLIT_TYPE", fallback: "auto"),
        ConfigKey(key: "auto_balance", env: "YABAI_AUTO_BALANCE", fallback: "off"),
        ConfigKey(
            key: "insert_feedback_color", env: "YABAI_INSERT_FEEDBACK_COLOR", fallback: "0x01000000"
        ),
        ConfigKey(key: "top_padding", env: "YABAI_TOP_PADDING", fallback: "8"),
        ConfigKey(key: "bottom_padding", env: "YABAI_BOTTOM_PADDING", fallback: "8"),
        ConfigKey(key: "left_padding", env: "YABAI_LEFT_PADDING", fallback: "8"),
        ConfigKey(key: "right_padding", env: "YABAI_RIGHT_PADDING", fallback: "8"),
        ConfigKey(key: "window_gap", env: "YABAI_WINDOW_GAP", fallback: "8"),
        ConfigKey(key: "mouse_follows_focus", env: "YABAI_MOUSE_FOLLOWS_FOCUS", fallback: "off"),
        ConfigKey(key: "mouse_modifier", env: "YABAI_MOUSE_MODIFIER", fallback: "ctrl"),
        ConfigKey(key: "mouse_action1", env: "YABAI_MOUSE_ACTION1", fallback: "move"),
        ConfigKey(key: "mouse_action2", env: "YABAI_MOUSE_ACTION2", fallback: "resize"),
        ConfigKey(key: "mouse_drop_action", env: "YABAI_MOUSE_DROP_ACTION", fallback: "stack")
    ]

    /// Splits an existing hand-written yabairc into the parts the app owns
    /// (config assignments) and the parts it must not touch — the scripting
    /// addition, signal handlers and helper invocations, none of which are data.
    static func seedRegions(from text: String) -> (signals: String, rules: String) {
        var signals: [String] = []
        var rules: [String] = []

        for raw in text.split(separator: "\n", omittingEmptySubsequences: false) {
            let line = String(raw)
            let trimmed = line.trimmingCharacters(in: .whitespaces)
            if trimmed.hasPrefix("#!") { continue }
            if trimmed.contains("yabai -m config ") { continue }
            if trimmed.contains("yabai -m rule ") { rules.append(line); continue }
            // Section comments that belong to config blocks go with them.
            let configHeadings = [
                "# BSP layout", "# Padding and gaps", "# Mouse controls",
                "# Float system apps"
            ]
            if configHeadings.contains(where: { trimmed.hasPrefix($0) }) { continue }
            signals.append(line)
        }

        return (Self.tidy(signals), Self.tidy(rules))
    }

    func generateYabaiRC() {
        let file = Self.yabairc
        var kept = file.preservedRegions()

        // First run: carve the hand-written file into keep regions so nothing
        // that isn't configuration is lost.
        if kept["signals"] == nil || kept["rules"] == nil,
            let existing = try? String(contentsOf: file.url, encoding: .utf8) {
            let seeded = Self.seedRegions(from: existing)
            if kept["signals"] == nil { kept["signals"] = seeded.signals }
            if kept["rules"] == nil { kept["rules"] = seeded.rules }
        }

        let config = Self.yabaiKeys
            .map { "yabai -m config \($0.key) \"${\($0.env):-\($0.fallback)}\"" }
            .joined(separator: "\n")

        let content = """
            #!/usr/bin/env bash
            # Generated by Macarchy Settings — edits here are reported, not silently kept.
            #
            # Config values resolve from settings.env at run time, so this is correct at
            # login whether or not the app is running. Everything inside macarchy:keep
            # is yours and survives regeneration — the scripting addition, signal
            # handlers and rules are not configuration and are never rewritten.

            SETTINGS_ENV="$HOME/.config/macarchy-settings/settings.env"
            if [ -f "$SETTINGS_ENV" ]; then
              # shellcheck source=/dev/null
              source "$SETTINGS_ENV"
            fi

            \(keepBlock("signals", from: kept))

            # Layout, padding and mouse — owned by the Layout pane.
            \(config)

            \(keepBlock("rules", from: kept))

            """

        record("yabairc", file.write(content, reason: "layout settings changed"))
    }
}
